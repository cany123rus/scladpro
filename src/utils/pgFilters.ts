/**
 * Список значений для фильтра PostgREST `in`, безопасный для кодов Честного знака.
 *
 * supabase-js в `.in(col, values)` берёт значение в кавычки, только если в нём
 * есть запятая или скобка, а кавычки и обратные слэши внутри не экранирует. В
 * хвосте марки ЧЗ встречаются и `"`, и `,` одновременно — такой код `.in()`
 * молча не находит (проверено 14.09.2026: 0 из 19). Отсюда были «код забрал
 * другой компьютер» при печати из базы и незамеченные дубли.
 *
 * Использование: `.filter('code', 'in', pgInList(codes))` вместо `.in('code', codes)`.
 */
export const pgInList = (values: readonly unknown[]) =>
  `(${values
    .map((v) => `"${String(v ?? '').replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`)
    .join(',')})`;
