/**
 * Перезагрузка за свежими кусками приложения.
 *
 * После деплоя старые чанки с хешами в именах исчезают, и вкладка, открытая до
 * него, падает на ленивом импорте. Лечится перезагрузкой — но делать её без
 * памяти нельзя, иначе получится петля. Раньше флаг ставился на всю сессию:
 * второй деплой за день такая вкладка уже не переживала и показывала ошибку.
 * Теперь помним время: повтор разрешён, но не чаще раза в две минуты.
 */
export function chunkReloadAllowed(key: string, cooldownMs = 120_000) {
  const flag = `chunk-reload-${key}`;
  try {
    const at = Number(sessionStorage.getItem(flag) || 0);
    if (at && Date.now() - at < cooldownMs) return false;
    sessionStorage.setItem(flag, String(Date.now()));
  } catch {
    // Приватный режим: хранилища нет, перезагрузимся один раз — петли не будет.
  }
  return true;
}
